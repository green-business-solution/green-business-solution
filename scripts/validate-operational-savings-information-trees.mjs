import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  buildOperationalSavingsReview,
  checkReviewArtifacts,
  loadOperationalSavingsSources
} from "./generate-operational-savings-review-pages.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const sources = await loadOperationalSavingsSources(ROOT);
const review = buildOperationalSavingsReview(sources);
const errors = [...review.errors];
const sourceUrls = [...new Set(sources.standardDocument.match(/https:\/\/[^)\s]+/g) || [])];

errors.push(...await checkReviewArtifacts(ROOT, review.artifacts));
await validateGeneratedPages(review, errors);
validateCanonicalIndex(review, sources.treeDocument, errors);
validateComStockAllowlist(review, errors);
validateNarrativeTotals(review, sources, sourceUrls, errors);

const report = {
  categories: review.report.categories,
  categoryPages: review.report.categoryPages,
  taxonomyRetrofits: review.report.taxonomyRetrofits,
  mappedRetrofits: review.report.mappedRetrofits,
  missingMappings: countErrors(errors, /^missing retrofit mapping:/),
  duplicateMappings: countErrors(errors, /^duplicate retrofit mapping:/),
  sharedBranches: review.report.sharedBranchesExpanded,
  standards: review.report.standardsEmbedded,
  standardsWithAutomation: review.standards.filter((standard) => hasCompleteAutomation(standard)).length,
  sourceUrls: sourceUrls.length,
  maxAtomicUserInputs: review.report.maxAtomicUserInputs,
  requiredUserInputs: review.report.requiredUserInputs,
  optionalKnownDetails: review.report.optionalKnownDetails,
  maxRequiredUserInputs: review.report.maxRequiredUserInputs,
  categoriesOverFourUserInputs: review.report.categoriesOverFourUserInputs,
  categoriesWithFiveUserInputs: review.report.categoriesWithFiveUserInputs,
  categoryStatuses: review.report.categoryStatuses,
  standardStatuses: review.report.standardStatuses,
  sourceEvidenceRecords: sources.evidenceManifest.evidence_records.length,
  sourceEvidenceStatuses: countBy(sources.evidenceManifest.evidence_records, "evidence_status"),
  formulaTermGroups: sources.categoryContracts.categories.reduce(
    (total, category) => total + category.formula_terms.length,
    0
  ),
  formulaTerms: sources.categoryContracts.categories.reduce(
    (total, category) => total + category.formula_terms.reduce(
      (categoryTotal, group) => categoryTotal + group.names.length,
      0
    ),
    0
  ),
  categoryManualVerdicts: sources.categoryContracts.categories.filter(
    (category) => String(category.manual_review_verdict || "").trim()
  ).length,
  standardManualVerdicts: sources.evidenceManifest.standards.filter(
    (standard) => String(standard.manual_review_verdict || "").trim()
  ).length,
  readyGoldenFixtures: sources.goldenFixtures.size
};

if (errors.length > 0) {
  console.error(JSON.stringify(report, null, 2));
  console.error("\nValidation failed:");
  for (const error of [...new Set(errors)]) console.error(`- ${error}`);
  process.exitCode = 1;
} else {
  console.log(JSON.stringify(report, null, 2));
  console.log("Operational-savings information-tree and generated-review validation passed.");
}

async function validateGeneratedPages(result, validationErrors) {
  const requiredSections = [
    "## Review Status",
    "## Retrofits",
    "## Primary Formula",
    "## Supporting Formula(s)",
    "## Formula-Term Evidence",
    "## Source-Role Evidence",
    "## Default-Path Proof",
    "## Fully Expanded Information Tree",
    "## Input Workflow",
    "## Standards and Automation",
    "## Category Notes and Missing-Data Behavior",
    "## Human Review Decisions"
  ];
  const automationFields = [
    "Selected Strategy",
    "Automation Method",
    "Difficulty",
    "Efficient Build-Time Estimate",
    "Expected Accuracy or Uncertainty",
    "Basis",
    "Why This Is the Best Value-for-Time Strategy",
    "Access, Refresh, Versioning, and Maintenance Requirements"
  ];

  for (const category of result.categoryReviews) {
    const relativePath = `docs/operational-savings-review/categories/${category.id}.md`;
    const page = await readFile(join(ROOT, relativePath), "utf8").catch(() => null);
    if (page === null) continue;
    if (!page.includes("GENERATED REVIEW VIEW") || !page.includes("Do not edit this file directly.")) {
      validationErrors.push(`${category.id} generated page is missing the generated-file notice`);
    }
    let previous = -1;
    for (const section of requiredSections) {
      const index = page.indexOf(section);
      if (index < 0) validationErrors.push(`${category.id} generated page is missing ${section}`);
      if (index >= 0 && index <= previous) validationErrors.push(`${category.id} generated page has ${section} out of order`);
      if (index >= 0) previous = index;
    }

    const tree = between(page, "## Fully Expanded Information Tree", "## Input Workflow");
    if (/^[│ ]*[├└]─ BR-[A-Z0-9-]+\s*$/m.test(tree)) {
      validationErrors.push(`${category.id} generated tree contains an unresolved bare shared-branch reference`);
    }
    if (/\{\{(?:lookup|constant|output|input|resource|component|intermediate):/.test(tree)) {
      validationErrors.push(`${category.id} generated tree exposes internal trace annotations`);
    }
    validateGeneratedTreeLabels(category, tree, validationErrors);

    const formulaEvidence = between(page, "## Formula-Term Evidence", "## Source-Role Evidence");
    if (!formulaEvidence.includes("| Formula term | Unit | Source or resolver | Exact path |")) {
      validationErrors.push(`${category.id} generated Formula-Term Evidence lacks the canonical matrix`);
    }
    for (const group of category.semanticContract.formula_terms) {
      for (const name of group.names) {
        if (!formulaEvidence.includes(`| ${name} |`)) {
          validationErrors.push(`${category.id} generated Formula-Term Evidence is missing ${name}`);
        }
      }
    }
    const sourceEvidence = between(page, "## Source-Role Evidence", "## Default-Path Proof");
    for (const summary of category.sourceEvidence.standardSummaries) {
      if (!sourceEvidence.includes(`### ${summary.standard_id}`)) {
        validationErrors.push(`${category.id} generated Source-Role Evidence is missing ${summary.standard_id}`);
      }
    }
    const defaultProof = between(page, "## Default-Path Proof", "## Fully Expanded Information Tree");
    for (const field of [
      "Minimum required inputs",
      "Exact scenario",
      "Source fixture",
      "Low/base/high calculation",
      "Final result path",
      "Uncertainty",
      "Executable golden fixture",
      "Remaining gate"
    ]) {
      if (!defaultProof.includes(`**${field}:**`)) {
        validationErrors.push(`${category.id} generated Default-Path Proof is missing ${field}`);
      }
    }

    const reviewStatus = between(page, "## Review Status", "## Retrofits");
    const requiredCount = Number(reviewStatus.match(/\*\*Required User-input count:\*\* (\d+)/)?.[1]);
    const optionalCount = Number(reviewStatus.match(/\*\*Optional Known-Detail count:\*\* (\d+)/)?.[1]);
    if (requiredCount !== category.inputs.RequiredUser.length) {
      validationErrors.push(`${category.id} generated Required User-input count is ${requiredCount}; expected ${category.inputs.RequiredUser.length}`);
    }
    if (optionalCount !== category.inputs.OptionalUser.length) {
      validationErrors.push(`${category.id} generated Optional Known-Detail count is ${optionalCount}; expected ${category.inputs.OptionalUser.length}`);
    }
    for (const subsection of [
      "### Required User Inputs",
      "### Optional Known Details",
      "### Profile Inputs",
      "### Bill Inputs",
      "### Standard-Derived Assumptions"
    ]) {
      if (!page.includes(subsection)) validationErrors.push(`${category.id} generated page is missing ${subsection}`);
    }

    const standardBlock = between(page, "## Standards and Automation", "## Category Notes and Missing-Data Behavior");
    for (const standard of category.tracedStandards) {
      const heading = `### ■ ${standard.id} — ${standard.title}`;
      if (!standardBlock.includes(heading)) {
        validationErrors.push(`${category.id} generated page is missing embedded Standard ${standard.id}`);
        continue;
      }
      const card = sectionFromHeading(standardBlock, heading);
      if (!/\*\*Source:\*\*[\s\S]*https:\/\//.test(card)) {
        validationErrors.push(`${category.id} embedded Standard ${standard.id} is missing an inline source link`);
      }
      for (const field of automationFields) {
        if (!card.includes(`**${field}:**`)) {
          validationErrors.push(`${category.id} embedded Standard ${standard.id} is missing Automation field ${field}`);
        }
      }
      for (const field of [
        "Resolver Type",
        "Supported Scenarios",
        "Scenario Output Behavior",
        "Low/Base/High Rule",
        "Uncertainty Rule",
        "Exact Override",
        "Source Version",
        "Selected Class or Candidate Set",
        "Assumptions",
        "Editable",
        "No-Estimate Rule"
      ]) {
        if (!card.includes(`**${field}:**`)) {
          validationErrors.push(`${category.id} embedded Standard ${standard.id} is missing Resolution Contract field ${field}`);
        }
      }
      for (const input of standard.tracedInputs) {
        if (!card.includes(`\`${input.key}\``) || (!input.conditional && !card.includes("**Resolved by:**"))) {
          validationErrors.push(`${category.id} embedded Standard ${standard.id} is missing traceability for ${input.key}`);
        }
      }
    }
  }

  const index = await readFile(join(ROOT, "docs/operational-savings-review/README.md"), "utf8").catch(() => null);
  if (index === null) return;
  for (const category of result.categoryReviews) {
    const expectedLink = `./categories/${category.id}.md`;
    if (!index.includes(expectedLink)) validationErrors.push(`review index is missing link for ${category.id}`);
    const row = index.split("\n").find((line) => line.startsWith(`| [\`${category.id}\`]`));
    if (!row) {
      validationErrors.push(`review index is missing row for ${category.id}`);
      continue;
    }
    const cells = row.split("|").slice(1, -1).map((cell) => cell.trim());
    if (Number(cells[2]) !== category.inputs.RequiredUser.length) {
      validationErrors.push(`review index has incorrect Required User-input count for ${category.id}`);
    }
    if (Number(cells[3]) !== category.inputs.OptionalUser.length) {
      validationErrors.push(`review index has incorrect Optional Known-Detail count for ${category.id}`);
    }
  }
}

function validateGeneratedTreeLabels(category, block, validationErrors) {
  const categoryId = category.id;
  const code = block.match(/```text\n([\s\S]*?)\n```/)?.[1];
  if (!code) {
    validationErrors.push(`${categoryId} generated page has no expanded text tree`);
    return;
  }
  const lines = code.split("\n").filter(Boolean);
  const nodes = lines.map((line) => ({ depth: treeDepth(line), text: stripTreePrefix(line) }));
  const intermediateLabels = collectIntermediateLabels(category.expandedTree);
  for (let index = 1; index < nodes.length; index += 1) {
    const node = nodes[index];
    const next = nodes[index + 1];
    const terminal = !next || next.depth <= node.depth;
    if (
      terminal &&
      !intermediateLabels.has(node.text) &&
      !["(User)", "(Profile)", "(Bill)", "(Standard)"].some((label) => node.text.endsWith(label))
    ) {
      validationErrors.push(`${categoryId} generated terminal leaf lacks an allowed source label: ${JSON.stringify(node.text)}`);
    }
  }
}

function collectIntermediateLabels(root, labels = new Set()) {
  if (/\{\{intermediate:\s*[^}]+\}\}/.test(root.text)) {
    labels.add(stripInternalTags(root.text));
  }
  for (const child of root.children) collectIntermediateLabels(child, labels);
  return labels;
}

function validateCanonicalIndex(result, treeDocument, validationErrors) {
  const rows = [...treeDocument.matchAll(/^\| `(ITC-\d{2})` \| \[([^\]]+)\]\(operational-savings-review\/categories\/(ITC-\d{2})\.md\) \| ([^|]+) \| (\d+) \|$/gm)].map((match) => ({
    id: match[1],
    title: match[2].trim(),
    linkId: match[3],
    status: match[4].trim(),
    retrofitCount: Number(match[5])
  }));
  if (rows.length !== result.categories.length) {
    validationErrors.push(`Category Index has ${rows.length} linked rows; expected ${result.categories.length}`);
    return;
  }
  for (const category of result.categories) {
    const row = rows.find((candidate) => candidate.id === category.id);
    if (!row || row.linkId !== category.id || row.title !== category.title || row.status !== category.status || row.retrofitCount !== category.retrofits.length) {
      validationErrors.push(`${category.id} Category Index metadata or Full review link does not match its category section`);
    }
  }
}

function validateComStockAllowlist(result, validationErrors) {
  const standard = result.standards.find((item) => item.id === "STD-COMSTOCK-ANNUAL-DELTA");
  const category = result.categories.find((item) => item.id === "ITC-01");
  if (!standard || !category) return;
  const block = between(standard.body, "The reviewed taxonomy-to-measure allowlist is:", "**Automation:**");
  const rows = [...block.matchAll(/^\| `([^`]+)` \| (.+) \|$/gm)];
  if (JSON.stringify(rows.map((row) => row[1])) !== JSON.stringify(category.retrofits.map((retrofit) => retrofit.id))) {
    validationErrors.push("STD-COMSTOCK-ANNUAL-DELTA allowlist does not exactly match ITC-01 retrofit order");
  }
  for (const row of rows) {
    if (!/`(?:env|hvac|ltg)_\d{4}`/.test(row[2])) validationErrors.push(`ComStock allowlist row ${row[1]} has no recognized universal measure ID`);
  }
}

function validateNarrativeTotals(result, loadedSources, urls, validationErrors) {
  const report = result.report;
  const evidenceStatuses = countBy(loadedSources.evidenceManifest.evidence_records, "evidence_status");
  const formulaTermGroups = loadedSources.categoryContracts.categories.reduce(
    (total, category) => total + category.formula_terms.length,
    0
  );
  const formulaTerms = loadedSources.categoryContracts.categories.reduce(
    (total, category) => total + category.formula_terms.reduce(
      (categoryTotal, group) => categoryTotal + group.names.length,
      0
    ),
    0
  );
  const expectedCoverage = `The required result is ${report.categories} categories, ${report.taxonomyRetrofits} unique retrofit mappings, zero missing IDs, and zero duplicate IDs.`;
  if (!loadedSources.treeDocument.includes(expectedCoverage)) validationErrors.push("Coverage contract totals do not match the parsed documents and taxonomy");

  const overFour = report.categoriesOverFourUserInputs.join(", ");
  for (const line of [
    `- Categories: ${report.categories}.`,
    `- Generated standalone category pages: ${report.categoryPages}.`,
    `- Canonical retrofit mappings: ${report.mappedRetrofits}.`,
    `- Missing mappings: 0.`,
    `- Duplicate mappings: 0.`,
    `- Shared branches: ${report.sharedBranchesExpanded}.`,
    `- Canonical Standards: ${report.standardsEmbedded}.`,
    `- Expanded maximum atomic User inputs per category: ${report.maxAtomicUserInputs}.`,
    `- Expanded Required User inputs: ${report.requiredUserInputs}.`,
    `- Expanded Optional Known Details: ${report.optionalKnownDetails}.`,
    `- Maximum Required User inputs per category: ${report.maxRequiredUserInputs}.`,
    `- Categories above four Required User inputs: ${overFour}.`,
    `- Machine-readable source-evidence records: ${loadedSources.evidenceManifest.evidence_records.length}.`,
    `- Source-evidence statuses: ${Object.entries(evidenceStatuses).map(([status, count]) => `${status} ${count}`).join(", ")}.`,
    `- Formula-term groups: ${formulaTermGroups}.`,
    `- Individual formula terms: ${formulaTerms}.`,
    `- Recorded category manual verdicts: ${loadedSources.categoryContracts.categories.length}.`,
    `- Recorded Standard manual verdicts: ${loadedSources.evidenceManifest.standards.length}.`,
    `- Executable Ready-category golden fixtures: ${loadedSources.goldenFixtures.size}.`
  ]) {
    if (!loadedSources.auditDocument.includes(line)) validationErrors.push(`audit summary is stale or missing: ${line}`);
  }
  if (!loadedSources.auditDocument.includes(`Link validation covered ${urls.length} unique direct registry URLs.`)) {
    validationErrors.push("audit link-validation total does not match the Standard registry");
  }
  for (const topic of [
    "generated review workflow",
    "source-role evidence",
    "formula-term evidence",
    "default-path proof",
    "formula/tree corrections",
    "semantic source audit",
    "formula audit",
    "default executability audit",
    "implementation readiness audit",
    "mutation tests",
    "unsupported claims removed",
    "manual review record",
    "atomic User-input review",
    "unresolved blockers",
    "High-uncertainty Standards",
    "A1 - Integration and sync",
    "A2 - Adversarial correctness",
    "A3 - Release readiness"
  ]) {
    if (!loadedSources.auditDocument.toLowerCase().includes(topic.toLowerCase())) validationErrors.push(`audit is missing required topic: ${topic}`);
  }
}

function hasCompleteAutomation(standard) {
  return [
    "**Selected Strategy:**",
    "**Automation Method:**",
    "**Difficulty:**",
    "**Efficient Build-Time Estimate:**",
    "**Expected Accuracy or Uncertainty:**",
    "**Basis:**",
    "**Why This Is the Best Value-for-Time Strategy:**",
    "**Access, Refresh, Versioning, and Maintenance Requirements:**"
  ].every((field) => standard.fields["**Automation:**"].includes(field));
}

function sectionFromHeading(text, heading) {
  const start = text.indexOf(heading);
  const next = text.indexOf("\n### ■ ", start + heading.length);
  return text.slice(start, next < 0 ? text.length : next);
}

function between(text, start, end) {
  const startIndex = text.indexOf(start);
  const endIndex = text.indexOf(end, startIndex + start.length);
  if (startIndex < 0 || endIndex < 0) return "";
  return text.slice(startIndex + start.length, endIndex);
}

function treeDepth(line) {
  const prefix = line.match(/^(?:(?:│  |   ))*/)?.[0] || "";
  return prefix.length / 3 + (/^(?:│  |   )*(?:├─ |└─ )/.test(line) ? 1 : 0);
}

function stripTreePrefix(line) {
  return line.replace(/^(?:│  |   )*(?:├─ |└─ )?/, "").trim();
}

function countErrors(values, pattern) {
  return values.filter((value) => pattern.test(value)).length;
}

function countBy(values, field) {
  return Object.fromEntries(
    [...new Set(values.map((value) => value[field]))]
      .sort()
      .map((key) => [key, values.filter((value) => value[field] === key).length])
  );
}

function stripInternalTags(text) {
  return text.replace(
    /\s*\{\{(?:lookup|constant|output|input|resource|component|intermediate):\s*[^}]+\}\}/g,
    ""
  ).trim();
}
